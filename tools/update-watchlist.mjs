// node tools/update-watchlist.mjs [region] [size]     (defaults: eu 80)
// Rebuilds dsh-web/watchlist.js: the common items with the largest turnover, which wow_flip_market judges on every
// question. Source: Forever AH's public API (see dsh-web/foreverah.js), the region's pooled "All Auction Houses".
// Candidates are the 400 items with the most units and the 400 with the most auctions; kept are trade goods,
// consumables and containers (no weapons or armor: single pieces, their market value says little) that have two weeks
// of history, ranked by gold sold a day (units sold a day x market value). About 9 requests, one a second.
// Run it when the market has moved on (a new phase, new items), then run the tests and release as usual.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeApi, housesUrl, IDS_MAX } from '../dsh-web/foreverah.js';

const region = process.argv[2] || 'eu';
const size = Math.min(IDS_MAX, Math.max(10, Number(process.argv[3]) || 80));
const CLASSES = new Set([0, 1, 7]);   // Consumable, Container, Trade Goods
const PAGES = [0, 100, 200, 300];
const MIN_DAYS = 14, MIN_SOLD = 1000, MIN_LISTINGS = 100;   // region-wide

const api = makeApi();
const houses = await api(housesUrl());
const all = houses.find((h) => h.region === region && h.house_type === 'unified');
if (!all) throw new Error(`no pooled house for region ${region}`);
const rows = new Map();
for (const sort of ['quantity', 'listings']) {
  for (const offset of PAGES) {
    const page = await api(`https://forever-ah.com/v1/houses/${all.house_key}/market?sort=${sort}&order=desc&window=24&limit=100&offset=${offset}`);
    for (const r of page.rows ?? []) rows.set(r.item.item_id, r);
  }
}
const gold = (r) => r.stats.sold_per_day * r.stats.market_value;
const kept = [...rows.values()]
  .filter((r) => r.item?.name && CLASSES.has(r.item.item_class_id) && r.stats?.market_value > 0
    && r.stats.days_seen >= MIN_DAYS && r.stats.sold_per_day >= MIN_SOLD && r.current?.listings >= MIN_LISTINGS)
  .sort((a, b) => gold(b) - gold(a))
  .slice(0, size);
if (kept.length < size) throw new Error(`only ${kept.length} items qualify (wanted ${size}): the list was not written`);

const date = new Date().toISOString().slice(0, 10);
const lines = [
  `// Generated by tools/update-watchlist.mjs on ${date}: do not edit by hand, run the script again.`,
  `// The ${size} common items with the largest turnover (gold sold a day) on WoW Forever ${region.toUpperCase()}, all auction houses pooled:`,
  '// trade goods, consumables and containers. Source: Forever AH (forever-ah.com, Blizzard Battle.net API).',
  '// The names are only for reading this file; answers use the names the API returns.',
  `export const WATCHLIST_DATE = '${date}';`,
  'export const WATCHLIST = [',
  ...kept.map((r) => `  [${r.item.item_id}, ${JSON.stringify(r.item.name)}],${' '.repeat(Math.max(1, 44 - String(r.item.item_id).length - JSON.stringify(r.item.name).length))}// ${r.item.item_class} / ${r.item.item_subclass}, about ${Math.round(gold(r) / 10000)} gold a day`),
  '];',
  'export const WATCH_IDS = WATCHLIST.map(([id]) => id);',
  '',
];
const file = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'dsh-web', 'watchlist.js');
fs.writeFileSync(file, lines.join('\n'));
console.log(`wrote ${kept.length} items to ${file} (from ${rows.size} candidates, region ${region})`);
